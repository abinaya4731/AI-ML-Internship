import numpy as np
a = np.array([10,20,30])
b = np.array([1,2,3])

#Q1: Add two arrays.
c = a + b
print(c)

#Q2: Subtract two arrays.
d = a - b
print(d)

#Q3: Multiply two arrays.
e = a * b
print(e)

#Q4: Divide two arrays.
f = a / b
print(f)

#Q5: Find the square of all elements.
g = np.square(a)
print(g)

#Q6: Find the cube of all elements.
h = np.power(a, 3)
print(h)

#Q7: Find the sum of all elements.
i = np.sum(a)
print(i)

#Q8: Find the maximum value.
j = np.max(a)
print(j)

#Q9: Find the minimum value.
k = np.min(a)
print(k)

#Q10: Find the average value.
l = np.mean(a)
print(l)